def test_empty_skill_registry_guarantees() -> None:
    """EMPTY_SKILL_REGISTRY is frozen, contains 0 skills, and produces 0 actions."""
    assert EMPTY_SKILL_REGISTRY.is_frozen
    assert len(EMPTY_SKILL_REGISTRY.skills) == 0
    assert len(EMPTY_SKILL_REGISTRY.skill_ids) == 0
    assert EMPTY_SKILL_REGISTRY.registry_identity != ""

    runtime = AuthoritativeSkillRuntime(EMPTY_SKILL_REGISTRY)
    assert len(runtime.player_skills) == 0

    session = FormalNoSkillDuelSession(configuration=FormalDuelConfiguration.formal_profile(), seed=1)
    context = ActionContext(mode="formal_duel", phase="play", actor_id="p1")
    actions = runtime.enumerate_active_skill_actions("p1", context, session.state)
    assert len(actions) == 0


