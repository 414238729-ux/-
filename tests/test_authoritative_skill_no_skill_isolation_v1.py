def test_no_skill_modes_execute_normally() -> None:
    """A representative no-skill duel session initializes and runs cleanly without skill interference."""
    config = FormalDuelConfiguration.formal_profile()
    session = FormalNoSkillDuelSession(configuration=config, seed=42)

    assert session.state is not None
    assert len(session.state.cards) == 160
    assert session.is_finished is False

    # Legal actions generated by no-skill session contain no skill actions
    legal_actions = session.legal_actions()
    assert all(a.action_type != "activate_skill" for a in legal_actions)
    assert all(a.skill_id is None for a in legal_actions)


